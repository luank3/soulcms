<?php

declare(strict_types=1);

namespace SoulCMS\Routing;

use SoulCMS\Foundation\Paths;

/**
 * Persists the compiled route table between requests.
 *
 * Route compilation is pure CPU work that does not need to happen on every
 * request. The cache stores a signature of the route source files; when the
 * signature still matches, the compiled table is restored with a single
 * `require` (opcache friendly) instead of re-parsing the route definitions.
 */
final class RouteCache
{
    public function __construct(
        private string $file,
        private bool $disabled = false,
    ) {
    }

    /**
     * Load the cached route table, but only when it is still up to date.
     *
     * @param list<string> $sources the files the routes are built from
     * @return RouteCollection|null null when the cache is cold or stale
     */
    public function load(array $sources = []): ?RouteCollection
    {
        if ($this->disabled || !is_file($this->file)) {
            return null;
        }

        $data = require $this->file;

        if (!is_array($data) || !isset($data['routes'])) {
            return null;
        }

        // A cache that no longer matches the sources is worthless: it would
        // silently serve yesterday's routing table.
        if (!isset($data['signature']) || $data['signature'] !== $this->signature($sources)) {
            return null;
        }

        return RouteCollection::fromArray($data);
    }

    /**
     * @param list<string> $sources
     */
    public function save(RouteCollection $collection, array $sources = []): bool
    {
        $directory = dirname($this->file);

        if (!is_dir($directory)) {
            mkdir($directory, 0775, true);
        }

        $payload = [
            'signature' => $this->signature($sources),
            'routes' => $collection->toArray()['routes'],
        ];

        $contents = "<?php\n\n// Compiled route table - generated by SoulCMS.\nreturn " . var_export($payload, true) . ";\n";

        $temporary = $this->file . '.' . getmypid() . '.tmp';

        if (file_put_contents($temporary, $contents) === false) {
            return false;
        }

        if (!rename($temporary, $this->file)) {
            @unlink($temporary);

            return false;
        }

        opcache_invalidate($this->file, true);

        return true;
    }

    /**
     * @param list<string> $sources
     */
    public function isFresh(array $sources = []): bool
    {
        if ($this->disabled || !is_file($this->file)) {
            return false;
        }

        $data = require $this->file;

        if (!is_array($data) || !isset($data['signature'])) {
            return false;
        }

        return $data['signature'] === $this->signature($sources);
    }

    /**
     * @param list<string> $sources
     */
    private function signature(array $sources): string
    {
        $parts = [];

        foreach ($sources as $source) {
            $parts[] = is_file($source) ? (string) filemtime($source) : '0';
        }

        return hash('xxh128', implode('|', $parts));
    }

    public function path(): string
    {
        return $this->file;
    }

    public function defaultPath(): string
    {
        return Paths::cache('routes.php');
    }
}
